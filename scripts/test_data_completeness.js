'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const host = { innerHTML: '' };
const source = JSON.parse(fs.readFileSync(path.join(root, 'data/trades.json'), 'utf8'));
const payload = JSON.parse(fs.readFileSync(path.join(root, 'data/reference/data-completeness.json'), 'utf8'));
const context = vm.createContext({ console, Intl, Set, Date, source, payload,
  $: () => host, esc: value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;') });
vm.runInContext(fs.readFileSync(path.join(root, 'data-completeness.js'), 'utf8'), context);
const run = code => vm.runInContext(code, context);
run('updateDataCompleteness(payload, source); renderDataCompleteness()');
assert.equal((host.innerHTML.match(/<progress /g) || []).length, 16);
assert.match(host.innerHTML, /Noticias/);
assert.match(host.innerHTML, /Con datos/);
assert.match(host.innerHTML, /Sin datos/);
assert.match(host.innerHTML, /3 \/ 509 · 0,6 %/);
assert.match(host.innerHTML, /sin aplicar filtros/);
assert.match(host.innerHTML, /sin noticias encontradas también cuenta/);
run('updateDataCompleteness({...payload, sourceGeneratedAt:"stale"}, source); renderDataCompleteness()');
assert.doesNotMatch(host.innerHTML, /<progress/);
assert.match(host.innerHTML, /no está disponible/);
run('updateDataCompleteness({...payload, symbols:[...payload.symbols,"MISSING"]}, source); renderDataCompleteness()');
assert.doesNotMatch(host.innerHTML, /<progress/);
run('var emptySource={generatedAt:"empty",tradeCount:0,trades:[]}; var emptyPayload={schemaVersion:1,sourceGeneratedAt:"empty",tradeCount:0,symbols:[],fields:Object.fromEntries(dataCompletenessFields.map(([key])=>[key,[]]))}; updateDataCompleteness(emptyPayload,emptySource); renderDataCompleteness()');
assert.match(host.innerHTML, /0 \/ 0 · 0 %/);
assert.doesNotMatch(host.innerHTML, /NaN|Infinity/);
console.log('Data completeness bars passed.');
