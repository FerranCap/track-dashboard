'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.join(__dirname, '..');
const context = vm.createContext({ Intl, Date, Map, Number, Object, console, fetch: () => { throw Error('Unexpected network access'); }, esc: value => String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;') });
vm.runInContext(fs.readFileSync(path.join(root,'trade-price-chart.js'),'utf8'), context);
const run = code => vm.runInContext(code,context);
const dataset = JSON.parse(fs.readFileSync(path.join(root,'data/trades.json'),'utf8'));
const trades = dataset.trades.filter(t => t.symbol === 'BENF' && t.date === '2026-11-24');
const index = JSON.parse(fs.readFileSync(path.join(root,'data/prices/index.json'),'utf8'));
const session = index.tickers.BENF['2026-11-24'];
context.executionPayload = JSON.parse(fs.readFileSync(path.join(root,session.executionsFile),'utf8'));
for (const trade of trades) {
  context.trade = trade;
  const window = run('tradePriceWindow(trade)');
  assert.equal(window.start, Math.floor(Date.parse(trade.opened)/60000)*60-900);
  assert.equal(window.end, Math.floor(Date.parse(trade.closed)/60000)*60+960);
  assert(window.end-window.start < 45*60, 'View stays close to the trade');
  const fills = run('tradePriceFills(executionPayload,trade)');
  assert(fills.complete);
  assert.equal(fills.fills.length,trade.executionCount);
  assert(fills.fills.some(f => f.role === 'exit'));
  for (const source of session.sources) {
    context.payload = JSON.parse(fs.readFileSync(path.join(root,source.file),'utf8'));
    const result = run('tradePriceBars(payload,trade)');
    assert(result.bars.length > 0);
    assert(result.bars.length < context.payload.bars.length);
    assert.equal(result.window.start,window.start);
    assert.equal(result.window.end,window.end);
    const svg = run('priceChartSvg(tradePriceBars(payload,trade).bars,tradePriceWindow(trade),tradePriceFills(executionPayload,trade).fills,"BENF")');
    assert(svg.includes('trade-fill-marker'));
    assert(!svg.includes('Volumen por minuto'));
    assert(svg.includes('#baff45') || svg.includes('#ff5252')); 
    assert(!/NaN|Infinity/.test(svg));
  }
}
context.trade = {...trades[0], opened: '2026-11-24T13:25:13-05:00'};
assert.equal(run('tradePriceFills(executionPayload,trade).fills.length'),0, 'Stale execution evidence is rejected');
context.trade = {...trades[0], symbol:'AMD'};
assert.throws(() => run('tradePriceBars(payload,trade)'));
context.trade = {...trades[0], side:'SELL'};
assert.equal(run('tradePriceWindow(trade).start'), Math.floor(Date.parse(trades[0].opened)/60000)*60-900);
context.trades = trades;
const groupedWindow = run('tradePriceWindow(trades)');
assert.equal(groupedWindow.start, Math.floor(Math.min(...trades.map(t => Date.parse(t.opened))) / 60000) * 60 - 900);
assert.equal(groupedWindow.end, Math.floor(Math.max(...trades.map(t => Date.parse(t.closed))) / 60000) * 60 + 960);
assert.equal(groupedWindow.intervals.length, trades.length);
const combined = run('trades.flatMap(trade => tradePriceFills(executionPayload,trade).fills)');
assert.equal(combined.length, trades.reduce((total, trade) => total + trade.executionCount, 0));
context.combined = combined;
const groupedSvg = run('priceChartSvg(tradePriceBars(payload,trades).bars,tradePriceWindow(trades),combined,"BENF")');
assert.equal((groupedSvg.match(/class="trade-fill-marker"/g) || []).length, combined.length);
assert(!/NaN|Infinity/.test(groupedSvg));
const html = fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(!html.includes('calendar-price-margin'));
assert(!html.includes('calendar-price-trade'));
assert(!html.includes('calendar-price-panel'));
const calendar = fs.readFileSync(path.join(root,'calendar.js'),'utf8');
assert(calendar.indexOf('calendarPriceMarkup(index)') > calendar.indexOf('Curva de PnL'));
console.log('Price source isolation, grouped ticker windows, fixed 15-minute margin and real execution markers passed.');

async function checkTickerPanels() {
  const makeNode = () => ({ textContent: '', innerHTML: '', disabled: false, replaceChildren() { this.innerHTML = ''; }, addEventListener() {} });
  const makePanel = () => {
    const nodes = new Map();
    const panel = { isConnected: true, querySelector(selector) { if (!nodes.has(selector)) nodes.set(selector, makeNode()); return nodes.get(selector); } };
    const host = panel.querySelector('.trade-price-chart');
    host.closest = () => panel;
    host.querySelector = () => makeNode();
    return panel;
  };
  const panels = [makePanel(), makePanel()];
  context.document = { getElementById(id) { return panels[Number(id.split('-').at(-1))]; } };
  context.groupedStatistics = rows => [...new Map([...new Set(rows.map(t => t.symbol))].map(symbol => [symbol, rows.filter(t => t.symbol === symbol)]))];
  context.calendarPnlCurve = rows => [[rows[0].opened, 0], ...rows.map(trade => [trade.closed, trade.pnl])];
  context.signed = value => `${value > 0 ? '+' : ''}${value.toFixed(2)} ${context.pnlDisplayUnit === 'r' ? 'R' : 'USD'}`;
  context.pnlDisplayUnit = 'usd';
  context.renderedCurves = {};
  context.renderChart = (id, series, options) => { context.renderedCurves[id] = { id, series, options }; };
  context.fetch = async file => ({ ok: true, json: async () => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8')) });
  context.rows = [...trades, { ...trades[0], id: 'missing', symbol: 'MISSING' }];
  await run('renderCalendarTradeChart(rows)');
  const markup = panels[0].querySelector('.trade-price-chart').innerHTML;
  assert.equal((markup.match(/class="trade-fill-marker"/g) || []).length, combined.length);
  assert.equal((markup.match(/class="trade-pnl-label"/g) || []).length, trades.length);
  for (const trade of trades) assert(markup.includes(context.signed(trade.pnl)));
  assert(context.renderedCurves['calendar-ticker-chart-0'].series[0].values.length > trades.length);
  assert(context.renderedCurves['calendar-day-chart'].series[0].values.length > trades.length);
  assert(context.renderedCurves['calendar-day-chart'].options.timeTicks);
  const dailyPoints = context.renderedCurves['calendar-day-chart'].series[0].values;
  assert(Math.abs(dailyPoints.at(-1)[1] - context.rows.reduce((sum, trade) => sum + trade.pnl, 0)) < 1e-9, 'Combined minute and close-only curves reconcile to recorded PnL');
  assert(panels[1].querySelector('.trade-price-status').textContent.includes('MISSING'));
  assert.equal(panels[1].querySelector('.trade-price-chart').innerHTML, '');
  assert.equal(panels[0].querySelector('.trade-price-source').disabled, false);
  context.pnlDisplayUnit = 'r';
  context.sessionRiskAt = () => ({ risk: 100 });
  context.rows = trades.map(trade => ({ ...trade, pnl: trade.pnl / 100 }));
  await run('renderCalendarTradeChart(rows)');
  const rMarkup = panels[0].querySelector('.trade-price-chart').innerHTML;
  for (const trade of context.rows) assert(rMarkup.includes(context.signed(trade.pnl)));
  assert(!rMarkup.includes('USD</text>'));
  const watchlistPanel = makePanel();
  await run('renderWatchlistPriceChart') (watchlistPanel, context.rows);
  assert.equal((watchlistPanel.querySelector('.trade-price-chart').innerHTML.match(/class="trade-pnl-label"/g) || []).length, trades.length);
  assert(watchlistPanel.querySelector('.trade-price-chart').innerHTML.includes(' R'));
  const missingPanel = makePanel();
  await run('renderWatchlistPriceChart')(missingPanel, [{ ...trades[0], symbol: 'MISSING' }]);
  assert(missingPanel.querySelector('.trade-price-status').textContent.includes('No hay velas'));
  await Promise.all([run('renderCalendarTradeChart(rows)'), run('renderCalendarTradeChart([])')]);
  console.log('Ticker panels aggregate all real fills, isolate missing data and handle selection changes.');
}
checkTickerPanels().catch(error => { console.error(error); process.exitCode = 1; });
